export type Key = keyof typeof en;
export const strings: Record<Lang, typeof en> = { en, fr };

/** Locale used for dates and numbers. */
export const LOCALE: Record<Lang, string> = { en: 'en-GB', fr: 'fr-FR' };

export function useT(lang: Lang) {
  const dict = strings[lang];
  return (key: Key, vars: Record<string, string | number> = {}) =>
    dict[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

/** A path inside the site, in the given language ("p/dark-cloud/" -> "/fr/p/dark-cloud/"). */
export function localHref(lang: Lang, path = '') {
  const base = import.meta.env.BASE_URL.replace(/\/?$/, '/');
  return `${base}${lang === 'fr' ? 'fr/' : ''}${path}`;
}

/** getStaticPaths entries for a page that exists in every language. */
export const langPaths = () => LANGS.map((lang) => ({ params: { lang: lang === 'en' ? undefined : lang }, props: { lang } }));

export function formatDate(lang: Lang, iso: string) {
  return new Date(iso).toLocaleDateString(LOCALE[lang], { day: 'numeric', month: 'short', year: 'numeric' });
}

/** In the browser: the current page's language, and its translator. */
export function pageLang(): Lang {
  return document.documentElement.lang === 'fr' ? 'fr' : 'en';
}
export const tc = (key: Key, vars?: Record<string, string | number>) => useT(pageLang())(key, vars);
